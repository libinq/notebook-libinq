import uuid
from pathlib import Path
from typing import Dict, Any, List
from ..config import UPLOAD_DIR

def create_pptx_from_outline(data: Dict[str, Any]) -> Path:
    """
    Generate a real .pptx presentation file using python-pptx.
    """
    from pptx import Presentation
    from pptx.util import Inches, Pt
    from pptx.dml.color import RGBColor
    from pptx.enum.text import PP_ALIGN

    prs = Presentation()
    # 16:9 widescreen layout
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    title_slide_layout = prs.slide_layouts[0]
    bullet_slide_layout = prs.slide_layouts[1]

    # Theme colors
    navy_color = RGBColor(24, 43, 73)
    accent_color = RGBColor(20, 115, 230)
    dark_text = RGBColor(40, 45, 55)

    # 1. Title Slide
    title_slide = prs.slides.add_slide(title_slide_layout)
    title_shape = title_slide.shapes.title
    subtitle_shape = title_slide.placeholders[1]

    title_shape.text = data.get("title", "Presentation")
    subtitle_shape.text = data.get("subtitle", "Generated by Open Notebook Bilingual Studio")

    title_p = title_shape.text_frame.paragraphs[0]
    title_p.font.size = Pt(44)
    title_p.font.bold = True
    title_p.font.color.rgb = navy_color

    # 2. Content Slides
    for slide_info in data.get("slides", []):
        slide = prs.slides.add_slide(bullet_slide_layout)
        s_title = slide.shapes.title
        s_title.text = slide_info.get("title", f"Slide {slide_info.get('slide_number', '')}")
        
        title_para = s_title.text_frame.paragraphs[0]
        title_para.font.size = Pt(32)
        title_para.font.bold = True
        title_para.font.color.rgb = navy_color

        body_shape = slide.placeholders[1]
        tf = body_shape.text_frame
        tf.word_wrap = True

        bullets = slide_info.get("bullets", [])
        for i, bullet in enumerate(bullets):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            p.text = bullet
            p.font.size = Pt(20)
            p.font.color.rgb = dark_text
            p.space_after = Pt(14)

        # Speaker notes
        notes = slide_info.get("speaker_notes", "")
        if notes:
            notes_slide = slide.notes_slide
            text_frame = notes_slide.notes_text_frame
            text_frame.text = notes

    export_id = str(uuid.uuid4())
    output_path = UPLOAD_DIR / f"presentation_{export_id}.pptx"
    prs.save(str(output_path))
    return output_path
